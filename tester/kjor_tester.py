from playwright.sync_api import sync_playwright
from pathlib import Path
root=Path(__file__).resolve().parent.parent
html=(root/'index.html').read_text().replace('<link rel="stylesheet" href="styles.css">','').replace('<script defer src="app.js"></script>','')
css=(root/'styles.css').read_text()
js=(root/'app.js').read_text().replace("document.addEventListener('DOMContentLoaded',init);",'window.__debug=()=>state.sets.map(s=>[s.id,minDepth(s),condition(s).key]);init();')
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[]
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.set_content(html)
 page.add_style_tag(content=css)
 page.evaluate("Object.defineProperty(window,'localStorage',{configurable:true,value:{_items:{},getItem(k){return this._items[k]||null},setItem(k,v){this._items[k]=v},removeItem(k){delete this._items[k]}}})")
 page.evaluate(js)
 print('title',page.title(),'overview',page.locator('.stat-card').count(), 'errors',errors)
 page.screenshot(path=str(root/'skjermbilder'/'01-oversikt.png'),full_page=True)
 page.locator('[data-view="hotels"]').click()
 print('hotels count',page.locator('tr[data-id]').count())
 page.locator('#hotelFilter').select_option('check')
 print('needs check',page.locator('tr[data-id]').count()); print('conditions',page.evaluate('window.__debug()'))
 page.locator('#hotelFilter').select_option('all')
 page.locator('[data-detail="H-101"]').click()
 print('detail',page.locator('#hotelDetail').inner_text()[:120])
 page.screenshot(path=str(root/'skjermbilder'/'02-dekkhotell.png'),full_page=True)
 page.locator('#openImport').click()
 page.locator('#csvFile').set_input_files(str(root/'testdata'/'eontyre_eksempel.csv'))
 page.locator('#importButton').click()
 page.wait_for_timeout(200)
 print('import status',page.locator('#importMessage').inner_text())
 print('after import rows',page.locator('tr[data-id]').count())
 assert '6 hjulsett' in page.locator('#importMessage').inner_text()
 assert 'DEMO123' not in page.locator('body').inner_text()
 page.locator('[data-view="offers"]').click()
 page.locator('input[name="price0"]').fill('4290')
 page.locator('input[name="price1"]').fill('6490')
 page.locator('input[name="price2"]').fill('8490')
 page.locator('button[type="submit"]').click()
 print('pub badge',page.locator('#offerVehicleInfo').inner_text())
 page.screenshot(path=str(root/'skjermbilder'/'03-tilbud.png'),full_page=True)
 page.locator('[data-view="customer"]').click()
 print('customer btn',page.locator('[data-customer-action="choose"]').count())
 page.screenshot(path=str(root/'skjermbilder'/'04-kundeapp.png'),full_page=True)
 page.locator('input[name="chooseOffer"][value="2"]').check()
 page.locator('[data-customer-action="choose"]').click()
 print('confirmation',page.locator('.phone-confirmation').inner_text())
 page.locator('[data-view="overview"]').click()
 print('responded',page.locator('#responseList').inner_text()[:160])
 page.locator('[data-confirm="IMP-001"]').click()
 assert 'Bekreftet' in page.locator('#responseList').inner_text()
 print('local save',page.evaluate("JSON.parse(localStorage.getItem('autolounge-min-garasje-school-v1')).sets[0].response.status"))
 snapshot=page.evaluate("localStorage.getItem('autolounge-min-garasje-school-v1')")
 page2=browser.new_page(viewport={'width':1280,'height':820})
 page2.set_content(html)
 page2.add_style_tag(content=css)
 page2.evaluate("""(snapshot) => {Object.defineProperty(window,'localStorage',{configurable:true,value:{_items:{'autolounge-min-garasje-school-v1':snapshot},getItem(k){return this._items[k]||null},setItem(k,v){this._items[k]=v},removeItem(k){delete this._items[k]}}})}""",snapshot)
 page2.evaluate(js)
 assert 'Bekreftet' in page2.locator('#responseList').inner_text()
 print('rehydration verified in fresh page')
 page2.close()
 page.locator('#resetButton').click()
 page.locator('#confirmReset').click()
 assert page.locator('tr[data-id]').count()==7
 page.locator('[data-view="customer"]').click()
 page.locator('[data-customer-action="callback"]').click()
 page.locator('[data-view="overview"]').click()
 assert 'Ønsker å bli oppringt' in page.locator('#responseList').inner_text()
 print('callback verified')
 print('reset verified', 'errors',errors)
 page.locator('#resetButton').click()
 page.locator('#confirmReset').click()
 page.wait_for_timeout(3600)
 page.set_viewport_size({'width':390,'height':844})
 page.screenshot(path=str(root/'skjermbilder'/'05-mobil.png'),full_page=True)
 print('mobile overflow',page.evaluate('document.documentElement.scrollWidth - innerWidth'))
 page.locator('#mobileMenu').click()
 page.locator('[data-view="customer"]').click()
 page.wait_for_timeout(350)
 page.screenshot(path=str(root/'skjermbilder'/'06-mobil-kunde.png'),full_page=True)
 print('customer mobile overflow',page.evaluate('document.documentElement.scrollWidth - innerWidth'))
 browser.close()
